"""add canonical spreadsheet

ADR-0034: the six tables holding the spreadsheet source family - four for
the canonical workbook representation (workbook, worksheet, row, cell)
and two for the evidence observed in it (set, evidence item).

**Purely additive.** Six new tables and their indexes. No existing table,
column or constraint is touched anywhere. In particular
``engineering_evidence`` and ``engineering_evidence_spans`` are
untouched: their provenance columns stay NOT NULL and their key formula
stays fixed, because a cell has no page, no paragraph, no line and no
span, and loosening those columns to admit one would weaken the PDF
family's own guarantee.

The two lineages fork at the bytes and meet nowhere above, so no foreign
key here points at a canonical PDF or canonical text table.

``canonical_cells`` keeps a cell's literal and its formula's cached
result in **distinct column groups** (``literal_*`` / ``formula_*`` +
``cached_*``), so no SQL query can conflate what an engineer typed with
what some other application computed into the file. A formula row whose
``cached_*`` columns are all null records that no application has ever
computed a value there - never a blank, an empty string or a zero.

Every numeric column is ``Numeric``, never ``Float``. A rated current
that read back as 630.0000000000001 A would be a defect nobody could
explain to an engineer.

``artifact_identity`` is nullable on both root tables and is **not**
backfilled by any server default: an identity written by a migration
would be a claim about a derivation the migration never observed. The
unique constraint on (document_id, artifact_identity) is the
persistence-level idempotency backstop - re-deriving the same
computation cannot produce a second row, while any change upstream is a
different identity and therefore a new row alongside, never over, the
old one.
"""
